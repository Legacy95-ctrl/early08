    <h2>Help</h2>
    <p>Need help with ROBLOX? Here are some of the most common questions.</p>

    <h3>What is ROBLOX?</h3>
    <p>ROBLOX is a free virtual world where you build your own games, play games made by other players, and chat with friends. You create a character &ndash; your avatar &ndash; and explore places built entirely out of virtual bricks.</p>

    <h3>How do I play?</h3>
    <p>Create a free account, choose a character, and head over to the <a href="games.php">Games</a> page to start playing. You can also build your own place &ndash; every player gets a place to build on right away.</p>

    <h3>How do I get ROBUX and Tickets?</h3>
    <p>ROBUX is the principal currency of ROBLOX. Citizens in the Builders Club receive a daily allowance of ROBUX. Tickets are earned by making cool places that other people visit. Visit the <a href="trade.php">Currency Exchange</a> to convert between the two.</p>

    <h3>How do I make friends?</h3>
    <p>Find someone you want to befriend in the <a href="users.php">People</a> directory or on a place, then visit their profile and send them a friend request.</p>

    <h3>How do I report abuse?</h3>
    <p>Use the Report Abuse link on any profile, place, or catalog item, or read more in our <a href="terms.php">Terms and Conditions</a>.</p>

    <p>Still stuck? Email our support team at <a href="mailto:info@roblox.com">info@roblox.com</a>.</p>
